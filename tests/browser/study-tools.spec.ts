import { test, expect } from '@playwright/test';
test('restored course tools edit the player, expose terrain and export evidence', async ({
   page,
}) => {
   test.setTimeout(120000);
   const errors: string[] = [];
   page.on('pageerror', (error) => errors.push(error.message));
   await page.emulateMedia({ reducedMotion: 'reduce' });
   await page.goto('/#play');
   await expect(page.locator('#desktopPlay')).toBeVisible({ timeout: 30000 });
   await page.keyboard.press('Escape');
   await page.locator('#openStudyTools').click();
   await expect(page.locator('#studyCanvas')).toBeVisible();
   await expect(page.locator('#terrainStudyReadout')).toContainText('slope');
   await page.locator('[data-layer=contours]').check();
   await page.locator('[data-layer=slopes]').check();
   await page.locator('[data-layer=boundaries]').check();
   await page.locator('[data-layer=zones]').check();
   await page.locator('[data-layer=route]').check();
   await page.locator('[data-study=research]').click();
   await page.locator('#compareGround').click();
   await expect(page.locator('#groundComparison')).toContainText('Ordinary fairway');
   await page.locator('[data-study=profile]').click();
   await expect(page.locator('#studyProfile')).toBeVisible();
   await page.locator('[data-study=bag]').click();
   await expect(page.locator('#stockTable')).toContainText('Driver');
   await page.locator('[data-study=player]').click();
   await page.locator('[data-preset=touch]').click();
   await page.getByRole('button', { name: 'Apply player', exact: true }).click();
   await expect(page.locator('#playerNotice')).toHaveText('Player applied to future shots.');
   const file = page.waitForEvent('download');
   await page.locator('#exportPlayer').click();
   expect((await file).suggestedFilename()).toBe('purity-player.json');
   await page.screenshot({ path: 'test-results/restored-player.png' });
   await page.locator('[data-study=journal]').click();
   await page.locator('[data-start=putt]').click();
   await page.locator('#quietView').click();
   await expect(page.locator('#selectedClubName')).toHaveText('Putter');
   await expect(page.locator('#desktopLie')).toHaveText('green');
   await page.locator('#desktopGimme').click();
   await expect(page.locator('#desktopResult')).toContainText('not physically holed');
   await page.locator('#desktopPlay').click();
   await page.locator('#desktopPlay').click();
   await page.locator('#desktopPlay').click();
   await page.keyboard.press('Escape');
   await page.locator('#openStudyTools').click();
   await page.locator('[data-study=profile]').click();
   await expect(page.locator('#profileContext')).toContainText('Last recorded');
   await page.screenshot({ path: 'test-results/restored-shot-profile.png' });
   expect(errors).toEqual([]);
});
